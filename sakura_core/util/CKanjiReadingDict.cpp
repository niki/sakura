namespace {
	//! g_aKanjiReadingTableを1回だけ逆引き用に組み直したもの(漢字1文字->行のひらがな)
	struct KanjiToHiraMap {
		std::map<wchar_t, wchar_t>	mapKanjiToHira;

		KanjiToHiraMap()
		{
			for( size_t i = 0; i < _countof( g_aKanjiReadingTable ); ++i ){
				const wchar_t*	p = g_aKanjiReadingTable[i].pszKanjiChars;
				for( ; L'\0' != *p; ++p ){
					// 既に登録済みの漢字は上書きしない(同じ漢字が複数行に載っていた場合、先勝ち)
					mapKanjiToHira.insert( std::make_pair( *p, g_aKanjiReadingTable[i].cHira ) );
				}
			}
		}
	};
}

wchar_t GetHiraByKanji( wchar_t cKanji )
{
	static const KanjiToHiraMap	s_map;
	std::map<wchar_t, wchar_t>::const_iterator	it = s_map.mapKanjiToHira.find( cKanji );
	return ( s_map.mapKanjiToHira.end() != it ) ? it->second : L'\0';
}

