<?php
// PHP 数値リテラル サンプル (NKMM_FIX_NUMERIC_LANG_LITERAL)
$a1 = 123;               // 10進数
$a2 = 0xFF;               // 16進数
$a3 = 3.14;               // 浮動小数点

$b1 = 0b1010;             // 2進数リテラル(PHP 5.4+) ← 新規対応
$b2 = 0B1111_0000;        // 2進数 + 桁区切り記号
$b3 = 0o17;               // 8進数リテラル(PHP 8.1+) ← 新規対応
$b4 = 0O17;
$b5 = 1_000_000;          // 桁区切り記号(10進, PHP 7.4+) ← 新規対応
$b6 = 0xFF_FF;            // 桁区切り記号(16進)

echo $a1, $a2, $a3, $b1, $b2, $b3, $b4, $b5, $b6;
