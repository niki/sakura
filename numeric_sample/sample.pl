# Perl 数値リテラル サンプル (NKMM_FIX_NUMERIC_LANG_LITERAL)
my $a1 = 123;               # 10進数
my $a2 = 0xFF;               # 16進数
my $a3 = 3.14;               # 浮動小数点

my $b1 = 0b1010;             # 2進数リテラル ← 新規対応
my $b2 = 0B1111_0000;        # 2進数 + 桁区切り記号
my $b3 = 0o17;                # 8進数リテラル(5.34+) ← 新規対応
my $b4 = 0O17;
my $b5 = 1_000_000;          # 桁区切り記号(10進) ← 新規対応
my $b6 = 0xFF_FF;             # 桁区切り記号(16進)

print "$a1 $a2 $a3 $b1 $b2 $b3 $b4 $b5 $b6\n";
