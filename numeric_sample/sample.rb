# Ruby 数値リテラル サンプル (NKMM_FIX_NUMERIC_LANG_LITERAL)
a1 = 123               # 10進数
a2 = 0xFF               # 16進数
a3 = 3.14               # 浮動小数点

b1 = 0b1010             # 2進数リテラル ← 新規対応
b2 = 0B1111_0000        # 2進数 + 桁区切り記号
b3 = 0o17                # 8進数リテラル ← 新規対応
b4 = 0O17
b5 = 1_000_000          # 桁区切り記号(10進) ← 新規対応
b6 = 0xFF_FF             # 桁区切り記号(16進)

c1 = 1r                  # 有理数サフィックス ← 新規対応
c2 = 1.5r                # 有理数サフィックス(浮動小数点)
c3 = 1i                  # 虚数サフィックス ← 新規対応
c4 = 1.5i                # 虚数サフィックス(浮動小数点)
c5 = 1ri                 # 有理数+虚数の組み合わせ(r→iの順) ← 新規対応

puts [a1, a2, a3, b1, b2, b3, b4, b5, b6, c1, c2, c3, c4, c5].inspect
